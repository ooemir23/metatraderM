  function language() {
    try {
      const saved = localStorage.getItem(STORAGE_KEY);
      if (saved === "tr" || saved === "en") return saved;
    } catch (_) { /* Private browsing may block storage. */ }
    return (navigator.language || "tr").toLowerCase().startsWith("tr") ? "tr" : "en";
  }

  function translate(value) {
    if (language() !== "en" || typeof value !== "string") return value;
    const match = value.match(/^(\s*)([\s\S]*?)(\s*)$/);
    const raw = match ? match[2] : value;
    if (!raw) return value;
    let result = en[raw];
    if (result === undefined) {
      for (const [re, render] of patterns) {
        if (re.test(raw)) { result = raw.replace(re, render); break; }
      }
    }
    return result === undefined ? value : `${match[1]}${result}${match[3]}`;
  }

  function translateNode(node) {
    if (!node) return;
    if (node.nodeType === 3) {
      if (node.parentElement?.closest("script, style, textarea, [contenteditable='true'], [data-no-translate]")) return;
      const translated = translate(node.nodeValue);
      if (translated !== node.nodeValue) node.nodeValue = translated;
      return;
    }
    if (node.nodeType !== 1) return;
    if (node.matches("script, style, textarea, [data-no-translate]")) return;
    for (const attr of ["title", "placeholder", "aria-label"]) {
      const value = node.getAttribute(attr);
      if (value) {
        const translated = translate(value);
        if (translated !== value) node.setAttribute(attr, translated);
      }
    }
    for (const child of node.childNodes) translateNode(child);
  }

  function apply() {
    document.documentElement.lang = language();
    const selector = document.getElementById("language-select");
    if (selector) selector.value = language();
    if (language() === "en") {
      document.title = translate(document.title);
      translateNode(document.body);
    }
  }

  function setLanguage(next) {
    if (next !== "tr" && next !== "en") return;
    try { localStorage.setItem(STORAGE_KEY, next); } catch (_) { /* Session still works. */ }
    location.reload();
  }

  window.MT5I18n = { language, translate, apply, setLanguage };
  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", apply);
  else apply();
  if (typeof MutationObserver !== "undefined") {
    const observer = new MutationObserver(records => {
      if (language() !== "en") return;
      for (const record of records) {
        if (record.type === "characterData") translateNode(record.target);
        else if (record.type === "attributes") translateNode(record.target);
        else for (const node of record.addedNodes) translateNode(node);
      }
    });
    observer.observe(document.documentElement, {subtree: true, childList: true, characterData: true,
      attributes: true, attributeFilter: ["title", "placeholder", "aria-label"]});
  }
